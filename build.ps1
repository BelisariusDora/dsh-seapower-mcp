# Build SeaPowerAgentBridge.dll with the .NET Framework 4 csc compiler (C# 5 language level).
# Usage:
#   powershell -ExecutionPolicy Bypass -File tools\spmcp_v2\build.ps1
#   powershell -ExecutionPolicy Bypass -File tools\spmcp_v2\build.ps1 -Deploy
param(
    [switch]$Deploy,
    # Parallel agents build into their own output so two csc runs never fight over the
    # same file. The deployment copy always comes from the default path.
    [string]$Out = ''
)

$ErrorActionPreference = 'Stop'

$here     = $PSScriptRoot                      # tools\spmcp
$gameRoot = Split-Path -Parent (Split-Path -Parent $here)   # Sea Power
$managed  = Join-Path $gameRoot 'Sea Power_Data\Managed'
$src      = Join-Path $here 'src'
$outDir   = Join-Path $here 'build'
$outDll   = Join-Path $outDir 'SeaPowerAgentBridge.dll'
if ($Out -ne '') {
    if ([System.IO.Path]::IsPathRooted($Out)) { $outDll = $Out }
    else { $outDll = Join-Path $here $Out }
}

$csc = 'C:\Windows\Microsoft.NET\Framework64\v4.0.30319\csc.exe'
if (-not (Test-Path $csc)) { throw "csc.exe not found at $csc" }

$anchorDll = $env:ANCHORCHAIN_DLL
if (-not $anchorDll -or -not (Test-Path $anchorDll)) {
    $anchorDll = Join-Path (Split-Path -Parent (Split-Path -Parent $gameRoot)) 'workshop\content\1286220\3380210757\AnchorChain.dll'
}
if (-not (Test-Path $anchorDll)) { throw "AnchorChain.dll not found: $anchorDll" }

$refs = @(
    (Join-Path $managed 'mscorlib.dll'),
    (Join-Path $managed 'netstandard.dll'),
    (Join-Path $managed 'System.dll'),
    (Join-Path $managed 'System.Core.dll'),
    (Join-Path $managed 'UnityEngine.dll'),
    (Join-Path $managed 'UnityEngine.CoreModule.dll'),
    # UnityEngine.Input lives in its own module; without this the compiler reports
    # CS1069 asking for UnityEngine.InputLegacyModule.
    (Join-Path $managed 'UnityEngine.InputLegacyModule.dll'),
    # ImageConversion.EncodeToPNG lives in its own module; CS1070 asks for
    # UnityEngine.ImageConversionModule when a screenshot is encoded.
    (Join-Path $managed 'UnityEngine.ImageConversionModule.dll'),
    # ScreenCapture.CaptureScreenshotAsTexture has its own module too. Capturing the
    # composed frame (UI included) is only possible through ScreenCapture, not through
    # Camera.Render into a RenderTexture.
    (Join-Path $managed 'UnityEngine.ScreenCaptureModule.dll'),
    (Join-Path $managed 'Newtonsoft.Json.dll'),
    (Join-Path $managed 'UniRx.dll'),
    (Join-Path $managed 'Unity.Mathematics.dll'),
    (Join-Path $managed 'Unity.Entities.dll'),
    (Join-Path $managed 'ParadoxNotion.dll'),
    (Join-Path $managed 'Seapower-Scripts.dll'),
    (Join-Path $managed 'Noesis.NoesisGUI.dll'),
    (Join-Path $gameRoot 'BepInEx\core\BepInEx.dll'),
    (Join-Path $gameRoot 'BepInEx\core\0Harmony.dll'),
    $anchorDll
)

foreach ($r in $refs) {
    if (-not (Test-Path $r)) { throw "missing reference: $r" }
}

if (-not (Test-Path $outDir)) { New-Item -ItemType Directory -Path $outDir -Force | Out-Null }

# Build stamp. A generated source file carries the identity of THIS compile, and the same
# string is written next to the DLL. /ping reports both, so a game that is still running an
# older assembly says so instead of looking like a bridge bug: on 2026-11-05 a 647680-byte
# bridge sat in the mod folder while the running game kept a stale one, and every fix was
# measured against the wrong binary.
$buildStamp = (Get-Date).ToUniversalTime().ToString('yyyyMMddTHHmmssZ')
$buildInfo = Join-Path $src 'BuildInfo.g.cs'
$stampLines = @(
    '// <auto-generated>written by build.ps1 on every compile - do not edit, do not commit</auto-generated>',
    'internal static class BuildInfo',
    '{',
    ('    internal const string Stamp = "' + $buildStamp + '";'),
    '}'
)
Set-Content -Path $buildInfo -Value $stampLines -Encoding ASCII

$sources = Get-ChildItem -Path $src -Filter '*.cs' -File | ForEach-Object { $_.FullName }
if (-not $sources) { throw "no .cs files in $src" }

$cscArgs = @(
    '/nologo',
    '/noconfig',
    '/target:library',
    '/nostdlib+',
    '/optimize+',
    '/codepage:65001',
    '/warn:1',
    '/langversion:5',
    '/debug:pdbonly',
    "/out:$outDll"
)
foreach ($r in $refs) { $cscArgs += "/r:$r" }
foreach ($s in $sources) { $cscArgs += $s }

Write-Host "csc: $csc"
Write-Host "out: $outDll"
Write-Host "sources:"
$sources | ForEach-Object { Write-Host "  $_" }

& $csc @cscArgs
$code = $LASTEXITCODE
if ($code -ne 0) { throw "compile failed with exit code $code" }

if (-not (Test-Path $outDll)) { throw "compile reported success but no dll at $outDll" }
$info = Get-Item $outDll
Write-Host ("OK  {0}  ({1} bytes)" -f $info.FullName, $info.Length)
$sha = (Get-FileHash $outDll -Algorithm SHA256).Hash
$stampFile = Join-Path $outDir 'SeaPowerAgentBridge.build'
Set-Content -Path $stampFile -Value ($buildStamp + ' ' + $info.Length + ' ' + $sha) -Encoding ASCII
Write-Host ("build stamp      {0}" -f $buildStamp)

if ($Deploy) {
    # The legacy project owned 'dsh-spmcp' and its files were moved out on 2026-11-05, so v2
# took that slot over: it is the directory the game already has enabled, and deploying to a
# second directory with the same plugin id only produced a stale copy nobody loaded.
$modDir = Join-Path $gameRoot 'Sea Power_Data\StreamingAssets\dsh-spmcp'
    if (-not (Test-Path $modDir)) { New-Item -ItemType Directory -Path $modDir -Force | Out-Null }
    Copy-Item $outDll (Join-Path $modDir 'SeaPowerAgentBridge.dll') -Force
    $deployReadme = [IO.File]::ReadAllText((Join-Path $here 'doc\DEPLOY.md'), [Text.Encoding]::UTF8)
    $deployReadme = $deployReadme.Replace('../comms/DSH.md', 'harness/DSH/README.md').Replace('../comms/CODEX_DEPLOY.md', 'harness/Codex/README.md').Replace('../comms/DOCTOR.md', 'harness/DOCTOR.md')
    [IO.File]::WriteAllText((Join-Path $modDir 'README.md'), $deployReadme)
    Copy-Item $stampFile (Join-Path $modDir 'SeaPowerAgentBridge.build') -Force
    # AnchorChain is a separately installed loader; reference it for compilation only.
    $ini = Join-Path $here '_info.ini'
    if (Test-Path $ini) { Copy-Item $ini (Join-Path $modDir '_info.ini') -Force }
    & (Join-Path $here 'deploy_modules.ps1') -ModDir $modDir
    $harnessDir = Join-Path $modDir 'harness'
    $harnessFiles = @{
        'doctor.py' = 'doctor.py'
        'DOCTOR.md' = 'DOCTOR.md'
        'README.md' = 'HARNESS.md'
        'DSH\README.md' = 'DSH.md'
        'DSH\harness_link.js' = 'harness_link.js'
        'DSH\legacy\ticket_store.js' = 'ticket_store.js'
        'DSH\legacy\ticket_runtime.js' = 'ticket_runtime.js'
        'DSH\dsh_ticket_plugin.mjs' = 'dsh_ticket_plugin.mjs'
        'DSH\dsh_ticket_notifications.mjs' = 'dsh_ticket_notifications.mjs'
        'DSH\dsh_tailer.js' = 'dsh_tailer.js'
        'DSH\prompts\onceopen.md' = 'prompts\onceopen.md'
        'Codex\README.md' = 'CODEX_DEPLOY.md'
        'Codex\codex_link.js' = 'codex_link.js'
        'Codex\codex_chat.py' = 'codex_chat.py'
        'Codex\prompts\onceopen.md' = 'prompts\onceopen.md'
        'Codex\legacy\codex_link.js' = 'legacy\codex_link.js'
        'Codex\legacy\codex_desktop.ps1' = 'codex_desktop.ps1'
        'Codex\legacy\codex.target.example.json' = 'codex.target.example.json'
    }
    foreach ($entry in $harnessFiles.GetEnumerator()) {
        $destination = Join-Path $harnessDir $entry.Key
        New-Item -ItemType Directory -Path (Split-Path -Parent $destination) -Force | Out-Null
        Copy-Item -LiteralPath (Join-Path $here ('comms\' + $entry.Value)) -Destination $destination -Force
        if ($entry.Value -in @('DSH.md', 'CODEX_DEPLOY.md')) {
            $body = [IO.File]::ReadAllText($destination).Replace('(DOCTOR.md)', '(../DOCTOR.md)')
            [IO.File]::WriteAllText($destination, $body, (New-Object Text.UTF8Encoding($false)))
        }
    }

    Copy-Item -LiteralPath (Join-Path $here 'doc\deployment_layout.md') -Destination (Join-Path $modDir 'MODULES.md') -Force
    Copy-Item -LiteralPath (Join-Path $here 'doc\ticket_results_ui.md') -Destination (Join-Path $modDir 'harness\TICKET_DETAILS.md') -Force
    Copy-Item -LiteralPath (Join-Path $here 'doc\ticket_notifications.md') -Destination (Join-Path $modDir 'harness\TICKET_NOTIFICATIONS.md') -Force
    Copy-Item -LiteralPath (Join-Path $here 'doc\localization.md') -Destination (Join-Path $modDir 'harness\LOCALIZATION.md') -Force
    Copy-Item -LiteralPath (Join-Path $here 'doc\main_agent_mode.md') -Destination (Join-Path $modDir 'harness\MAIN_AGENT_MODE.md') -Force
    $settingsDoc = [IO.File]::ReadAllText((Join-Path $here 'doc\settings_page.md')).Replace('main_agent_mode.md', 'MAIN_AGENT_MODE.md')
    [IO.File]::WriteAllText((Join-Path $modDir 'harness\SETTINGS.md'), $settingsDoc)

    Copy-Item -LiteralPath (Join-Path $here 'doc\tickets_deployment.md') -Destination (Join-Path $modDir 'harness\DSH\TICKETS.md') -Force

    if (!(Test-Path -LiteralPath (Join-Path $modDir 'persona.md'))) {
        Copy-Item -LiteralPath (Join-Path $here 'persona.md') -Destination (Join-Path $modDir 'persona.md')
    }

    foreach ($folder in @('language_en', 'language_cn')) {
        $target = Join-Path $modDir ($folder + '\ui.ini')
        $defaults = Join-Path $here ('deployment\assets\' + $folder + '\ui.ini')
        $text = if (Test-Path -LiteralPath $target) { [IO.File]::ReadAllText($target) } else { "[AgentInspector]`n" }
        $present = @{}
        foreach ($line in ($text -split "`r?`n")) {
            if ($line -match '^\s*([^;#][^=]*?)\s*=') { $present[$matches[1].Trim()] = $true }
        }
        $added = @()
        foreach ($line in [IO.File]::ReadAllLines($defaults)) {
            if ($line -match '^\s*([^;#][^=]*?)\s*=') {
                $key = $matches[1].Trim()
                if (-not $present.ContainsKey($key)) { $added += $line; $present[$key] = $true }
            }
        }
        if ($added.Count -gt 0) {
            New-Item -ItemType Directory -Path (Split-Path -Parent $target) -Force | Out-Null
            [IO.File]::WriteAllText($target, $text.TrimEnd() + "`n`n[AgentInspector]`n" + ($added -join "`n") + "`n", (New-Object Text.UTF8Encoding($false)))
        }
    }

    $settings = Join-Path $modDir 'setting.ini'
    if (!(Test-Path -LiteralPath $settings)) {
        [IO.File]::WriteAllText($settings, "[MCP]`r`nCompactReplies=false`r`n")
    }
    $docFolder=Join-Path $modDir 'docs'
    New-Item -ItemType Directory -Path $docFolder -Force | Out-Null
    $moduleDocs=Get-Content -LiteralPath (Join-Path $here 'deployment\modules.json') -Raw -Encoding UTF8 | ConvertFrom-Json
    foreach($document in Get-ChildItem -LiteralPath (Join-Path $here 'doc') -File -Filter '*.md') {
        $body=[IO.File]::ReadAllText($document.FullName,[Text.Encoding]::UTF8)
        foreach($entry in $moduleDocs.PSObject.Properties) {
            $body=$body.Replace('(../'+$entry.Name+')','(../'+$entry.Value+')')
        }
        $body=$body.Replace('(../comms/DSH.md)','(../harness/DSH/README.md)').Replace('(../comms/CODEX_DEPLOY.md)','(../harness/Codex/README.md)')
        [IO.File]::WriteAllText((Join-Path $docFolder $document.Name),$body,(New-Object Text.UTF8Encoding($false)))
    }
    # Rebase source-doc links in the installed topical copies, without touching user files.
    foreach($relative in @('MODULES.md','harness\TICKET_DETAILS.md','harness\TICKET_NOTIFICATIONS.md','harness\SETTINGS.md','harness\MAIN_AGENT_MODE.md','harness\LOCALIZATION.md')) {
        $target=Join-Path $modDir $relative
        if(-not (Test-Path -LiteralPath $target)){continue}
        $body=[IO.File]::ReadAllText($target,[Text.Encoding]::UTF8)
        $prefix=if($relative.StartsWith('harness\')){'../docs/'}else{'docs/'}
        foreach($document in Get-ChildItem -LiteralPath (Join-Path $here 'doc') -File -Filter '*.md') {
            $body=$body.Replace('('+$document.Name+')','('+$prefix+$document.Name+')')
        }
        [IO.File]::WriteAllText($target,$body,(New-Object Text.UTF8Encoding($false)))
    }

    $startScript = Join-Path $here 'start_game.ps1'
    if (Test-Path $startScript) { Copy-Item $startScript (Join-Path $modDir 'start_game.ps1') -Force }
    # Read the destination back. A "deployed" line that was not verified is how a running
    # game kept an old bridge for hours while the build directory moved on: every later
    # measurement then described a binary that was never loaded. Hash both sides here so
    # the mismatch fails in this command instead of being discovered later by inference.
    $dstDll = Join-Path $modDir 'SeaPowerAgentBridge.dll'
    $srcHash = (Get-FileHash $outDll -Algorithm SHA256).Hash
    $dstHash = (Get-FileHash $dstDll -Algorithm SHA256).Hash
    if ($srcHash -ne $dstHash) {
        throw ("deploy verification failed: build {0} bytes {1} != deployed {2} bytes {3} - the game may still hold the dll" -f `
            (Get-Item $outDll).Length, $srcHash.Substring(0, 16), (Get-Item $dstDll).Length, $dstHash.Substring(0, 16))
    }
    # Record the verified hash next to the dll. docs/TOMORROW_ACCEPTANCE.md tells a human to
    # compare the deployed SHA256 against this file, and nothing wrote it: it was left over from
    # an old deploy, so the acceptance check reported a mismatch on a perfectly good deployment.
    Set-Content -Path (Join-Path $modDir 'deploy_sha.txt') -Value $dstHash -Encoding ASCII -NoNewline
    Write-Host ("deploy verified  {0} bytes  {1}" -f (Get-Item $dstDll).Length, $dstHash.Substring(0, 16))
    Write-Host ("deploy_sha.txt   {0}" -f $dstHash)
    Write-Host "deployed to $modDir"
}
